#!/usr/bin/env python3
"""Build scripts/lang/lang_pt.gd and lang_es.gd from tools/i18n/*.txt.

Entry format (blank line between entries, '#' starts a comment line):
    > English text, \\n for a line break
    pt Portuguese
    es Spanish
The English text is the key. Placeholders (%d %s %.1f ...) must match in all three.
Usage: python3 tools/i18n_build.py   (add a language: see docs/localisation.md)
"""
import glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LANGS = {"pt": ("LangPt", "Brazilian Portuguese"), "es": ("LangEs", "Spanish (Spain)")}
PH = re.compile(r"%[-+0#]*\d*(?:\.\d+)?[sdfxXc]|%%")


def unesc(s):
    return s.replace("\\n", "\n")


def gd(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'


def parse():
    entries = {}
    errors = []
    for path in sorted(glob.glob(os.path.join(HERE, "i18n", "*.txt"))):
        cur = None
        for n, line in enumerate(open(path, encoding="utf-8").read().split("\n"), 1):
            where = "%s:%d" % (os.path.basename(path), n)
            if line.startswith("#") or not line.strip():
                if cur is not None:
                    finish(cur, entries, errors)
                    cur = None
                continue
            if line.startswith("> "):
                if cur is not None:
                    finish(cur, entries, errors)
                cur = {"en": unesc(line[2:]), "where": where}
            elif line[:3] in ("pt ", "es ") and cur is not None:
                cur[line[:2]] = unesc(line[3:])
            else:
                errors.append("%s: cannot read line: %s" % (where, line[:60]))
        if cur is not None:
            finish(cur, entries, errors)
    return entries, errors


def finish(cur, entries, errors):
    en = cur["en"]
    for l in LANGS:
        if l not in cur:
            errors.append("%s: no %s for: %s" % (cur["where"], l, en[:60]))
            return
    ph = sorted(PH.findall(en))
    for l in LANGS:
        if sorted(PH.findall(cur[l])) != ph:
            errors.append("%s: placeholders differ in %s: %s" % (cur["where"], l, en[:60]))
    if en in entries:
        if any(entries[en][l] != cur[l] for l in LANGS):
            errors.append("%s: duplicate key with a different text: %s" % (cur["where"], en[:60]))
        return
    entries[en] = cur


def main():
    entries, errors = parse()
    for e in errors:
        print("ERROR", e)
    if errors:
        sys.exit(1)
    # UPPER-CASE twins: the menus show many names upper-cased in code (name.to_upper())
    for en in list(entries):
        up = en.upper()
        if up != en and up not in entries and "\n" not in en and len(en) <= 60 and "%" not in en:
            e = entries[en]
            entries[up] = {"en": up, "pt": e["pt"].upper(), "es": e["es"].upper(), "where": e["where"]}
    for l, (cls, name) in LANGS.items():
        out = ["class_name %s" % cls,
               "## %s. Generated by tools/i18n_build.py from tools/i18n/*.txt: edit those, not this." % name,
               "const T := {"]
        for en, e in entries.items():
            out.append("\t%s: %s," % (gd(en), gd(e[l])))
        out.append("}")
        open(os.path.join(ROOT, "scripts", "lang", "lang_%s.gd" % l), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("%d entries" % len(entries))


if __name__ == "__main__":
    main()
