"""Level every game sound to the music: writes scripts/sound_mix.gd, a gain (dB) per file,
so each sound's loudest moment matches the music's loudness as it plays in the game.
Run after adding or remaking sounds:  python3 tools/audio/make_mix.py"""
import glob, os, subprocess
import numpy as np

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
MUSIC_VOL = -8.0       # music.gd VOL
LIMIT = 12.0           # never push a file more than this up or down
# gentler on purpose (dB, added to the levelled gain): the grub is selected and sent off all game long;
# the Breeder's neigh is a loud sound for a building you click often
OFFSET = {"select/horse_breeder": -2.0, "voice/grub/select": -6.0, "voice/grub/move": -4.0, "voice/spitter/move": -2.0, "combat/grub_death": -3.0,
          "work/cog_press_stamp": -3.0}     # (the Cog Press stamps all game long: a quiet thud under the fight)

def load(p):
    raw = subprocess.run(["ffmpeg", "-v", "quiet", "-i", p, "-f", "f32le", "-ac", "1", "-ar", "22050", "-"],
                         capture_output=True).stdout
    return np.frombuffer(raw, dtype=np.float32)

def loud(x, win=0.3):
    """Loudness of the loudest `win` seconds (RMS, dB): what the ear takes as 'how loud'."""
    w = int(22050 * win)
    if len(x) <= w:
        return 20 * np.log10(np.sqrt(np.mean(x ** 2)) + 1e-9)
    e = [np.sqrt(np.mean(x[i:i + w] ** 2)) for i in range(0, len(x) - w, w // 3)]
    return 20 * np.log10(max(e) + 1e-9)

music = [loud(load(f), 3.0) for f in glob.glob(os.path.join(ROOT, "assets/music/*.ogg"))]
target = float(np.median(music)) + MUSIC_VOL
files = [f for f in glob.glob(os.path.join(ROOT, "assets/audio/**/*.*"), recursive=True)
         + glob.glob(os.path.join(ROOT, "assets/voice/**/*.*"), recursive=True)
         if f.endswith((".wav", ".ogg")) and "/ambience/" not in f]
lines = []
for f in sorted(files):
    g = max(-LIMIT, min(LIMIT, target - loud(load(f))))
    g += sum(v for k, v in OFFSET.items() if k in f.replace(os.sep, "/"))
    rel = "res://" + os.path.relpath(f, ROOT).replace(os.sep, "/")
    lines.append('\t"%s": %.1f,' % (rel, g))
out = os.path.join(ROOT, "scripts/sound_mix.gd")
with open(out, "w") as fh:
    fh.write("class_name SoundMix\n## Generated by tools/audio/make_mix.py: a gain (dB) per sound file that brings its\n"
             "## loudest moment to the music's loudness in game (%.1f dB), so nothing is buried or blaring.\n" % target)
    fh.write("const GAIN := {\n" + "\n".join(lines) + "\n}\n")
print("target %.1f dB, %d files" % (target, len(lines)))
