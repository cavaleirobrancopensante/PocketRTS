#!/usr/bin/env python3
"""Build scripts/lang/patch_pt.gd and patch_es.gd (translated patch notes) from
tools/i18n/patch/notes.txt. Each line:  <version>#<item number> ;; <pt> ;; <es>
Items are numbered in the order they appear in scripts/patch_notes.gd (English stays the
authoritative text; a missing translation shows the English item).
Usage: python3 tools/i18n_patch_build.py"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def gd(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
src = open(os.path.join(ROOT, "scripts/patch_notes.gd"), encoding="utf-8").read()
counts = {}
for m in re.finditer(r'\{"v": "([^"]+)", "items": \[(.*?)\n\t\]\}', src, re.S):
    counts[m.group(1)] = len(re.findall(r'^\t\t"(?:[^"\\]|\\.)*",?$', m.group(2), re.M))
tr = {"pt": {}, "es": {}}
for n, line in enumerate(open(os.path.join(ROOT, "tools/i18n/patch/notes.txt"), encoding="utf-8"), 1):
    line = line.rstrip("\n")
    if not line.strip() or line.startswith("#"): continue
    p = line.split(" ;; ")
    if len(p) != 3: sys.exit("notes.txt:%d: need 'key ;; pt ;; es'" % n)
    v, i = p[0].split("#")
    if v not in counts or int(i) >= counts[v]: sys.exit("notes.txt:%d: unknown item %s" % (n, p[0]))
    tr["pt"].setdefault(v, {})[int(i)] = p[1].strip()
    tr["es"].setdefault(v, {})[int(i)] = p[2].strip()
for code, cls in (("pt", "PatchPt"), ("es", "PatchEs")):
    out = ["class_name %s" % cls, "extends RefCounted",
           "## GENERATED by tools/i18n_patch_build.py from tools/i18n/patch/notes.txt. Do not edit.",
           "## Patch notes in %s: version -> items in the order of scripts/patch_notes.gd ('' = show the English)." % code, "", "const N := {"]
    for v in counts:
        items = [tr[code].get(v, {}).get(i, "") for i in range(counts[v])]
        if any(items):
            out.append("\t%s: [%s]," % (gd(v), ", ".join(gd(x) for x in items)))
    out.append("}")
    open(os.path.join(ROOT, "scripts/lang/patch_%s.gd" % code), "w", encoding="utf-8").write("\n".join(out) + "\n")
miss = [v for v in counts if v not in tr["pt"]]
print("built; versions without translation:", miss)
