"""More terrain: the biome atlas art/world/terrain/tiles_c.png (29 sets on dark navy, each
2 rows of tiles: ground variants, then a cliff block at the right end of most).
-> assets/terrain/<set>_<n>.png (32x32 ground), <set>_face_<n>.png (the cliff block's rock
   face) and <set>_top_<n>.png (its top), and scripts/terrain_data2.gd (counts, the variants
   that tile best, average colours).
   python3 tools/import_terrain2.py [contact_sheet.png]"""
import os
import sys
import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "art", "world", "terrain", "tiles_c.png")
OUT = os.path.join(ROOT, "assets", "terrain")
T = 32

ROWS = [(17, 162), (180, 328), (346, 495), (514, 662), (679, 827), (845, 991), (1008, 1156)]
COLS4 = [(21, 321), (345, 645), (669, 969), (993, 1291)]
NAMES = [["bone", "slate", "heather", "leaves"],
         ["roots", "fern", "chalk", "clay"],
         ["cinder", "frost", "bog", "deep"],
         ["rapids", "reeds", "steppe", "scrub"],
         ["pine", "mossrock", "canyon", "ruin"],
         ["rubble", "tundra", "glacier", "kelp"]]
# (set name, row, x0, x1, columns, has a cliff block at the right)
SETS = []
for r, names in enumerate(NAMES):
    for c, n in enumerate(names):
        SETS.append((n, r, COLS4[c][0], COLS4[c][1], 5, True))
SETS += [("coral", 6, 21, 320, 5, True), ("shingle", 6, 347, 574, 4, True),
         ("glow", 6, 598, 780, 3, False), ("burnt", 6, 788, 968, 3, True),
         ("heath", 6, 993, 1291, 5, True)]
NAVY = np.array([18, 34, 51])


def shrink(a, w, h):
    return np.array(Image.fromarray(a.astype(np.uint8)).resize((w, h), Image.BOX))


def save(a, name):
    Image.fromarray(a.astype(np.uint8)).convert("RGB").save(os.path.join(OUT, name + ".png"))


def seps(profile, lo, hi, n):
    """The block's edges and its n-1 inner separators: the darkest line near each even split."""
    out = [lo]
    w = (hi - lo) / n
    for k in range(1, n):
        e = int(lo + k * w)
        win = profile[e - 7:e + 8]
        out.append(e - 7 + int(np.argmin(win)))
    out.append(hi)
    return out


def main():
    a = np.array(Image.open(SRC).convert("RGB")).astype(int)
    bright = a.sum(-1)
    counts, good, colours = {}, {}, {}
    sheet = []
    for name, r, x0, x1, n, cliff in SETS:
        y0, y1 = ROWS[r]
        xs = seps(bright[y0:y1, :].mean(0), x0, x1, n)
        ys = seps(bright[:, x0:x1].mean(1), y0, y1, 2)
        ground = []
        for row in range(2):
            for col in range(n):
                ta, tb = ys[row] + 4, ys[row + 1] - 3
                la, lb = xs[col] + 4, xs[col + 1] - 3
                tile = a[ta:tb, la:lb]
                if cliff and col == n - 1:
                    h = tb - ta
                    save(shrink(tile[int(h * 0.42):], T, T), f"{name}_face_{row}")
                    save(shrink(tile[:int(h * 0.42)], T, T), f"{name}_top_{row}")
                    sheet.append(shrink(tile, T, T))
                    continue
                t = shrink(tile, T, T)
                ground.append(t)
                sheet.append(t)
        for i, t in enumerate(ground):
            save(t, f"{name}_{i}")
            # a border of navy left in a tile would show as a grid on the ground
            edge = np.concatenate([t[0], t[-1], t[:, 0], t[:, -1]]).astype(int)
            frac = (np.abs(edge - NAVY).sum(-1) < 40).mean()
            inner = (np.abs(t[4:-4, 4:-4].astype(int) - NAVY).sum(-1) < 40).mean()
            if frac > inner + 0.2:     # (a dark set is navy-ish all over: that's fine)
                print("navy edge?", name, i, round(frac, 2))
        counts[name] = len(ground)
        if cliff:
            counts[name + "_face"] = 2
            counts[name + "_top"] = 2
            good[name + "_face"] = [0, 1]
            good[name + "_top"] = [0, 1]
        tiles = [t.astype(float) for t in ground]
        means = np.array([t.reshape(-1, 3).mean(0) for t in tiles])
        med = np.median(means, 0)
        scores = []
        for i, t in enumerate(tiles):
            seam = np.abs(t[:, 0] - t[:, -1]).mean() + np.abs(t[0] - t[-1]).mean()
            scores.append(np.abs(means[i] - med).sum() * 1.5 + seam)
        good[name] = [int(i) for i in np.argsort(scores)[:4]]
        colours[name] = means.mean(0) / 255.0
    with open(os.path.join(ROOT, "scripts", "terrain_data2.gd"), "w") as f:
        f.write("class_name TerrainData2\n## Generated by tools/import_terrain2.py (the second biome atlas).\n\nconst COUNTS := {\n")
        for k, v in counts.items():
            f.write(f'\t"{k}": {v},\n')
        f.write("}\n\n## The variants that tile best, best first.\nconst GOOD := {\n")
        for k, v in good.items():
            f.write(f'\t"{k}": {v},\n')
        f.write("}\n\n## Average colour of each ground set (minimap, lobby preview).\nconst COLOURS := {\n")
        for k, m in colours.items():
            f.write(f'\t"{k}": Color({m[0]:.3f}, {m[1]:.3f}, {m[2]:.3f}),\n')
        f.write("}\n")
    print(len(SETS), "sets")
    return sheet


if __name__ == "__main__":
    sheet = main()
    if len(sys.argv) > 1:
        # a contact sheet of every cut tile, 10 to a row (for checking by eye)
        rows = []
        for i in range(0, len(sheet), 10):
            row = sheet[i:i + 10]
            row += [np.zeros((T, T, 3), np.uint8)] * (10 - len(row))
            rows.append(np.concatenate([np.pad(t, ((1, 1), (1, 1), (0, 0)), constant_values=255) for t in row], 1))
        img = Image.fromarray(np.concatenate(rows, 0).astype(np.uint8))
        img.resize((img.width * 2, img.height * 2), Image.NEAREST).save(sys.argv[1])
